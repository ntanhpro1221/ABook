def _docx(body, core, *, extra=()):
    with zipfile.ZipFile(io.BytesIO(_base_docx(body, core))) as archive:
        entries = {name: archive.read(name) for name in archive.namelist()}
    entries.update((name, text.encode()) for name, text in extra)
    return _zip(list(entries.items()))


def kotlin_casefold():
    rows = [f"        {code} to {json.dumps(chr(code).casefold())}," for code in range(0x110000) if chr(code).casefold() != chr(code)]
    return (f"// Generated by tests/a84_import_fixtures.py; Unicode {unicodedata.unidata_version}, Python casefold.\n"
            "package vn.abook.player\n\ninternal object ImportCaseFold {\n"
            "    private val folds = mapOf(\n" + "\n".join(rows) + "\n    )\n"
            "    fun fold(text: String): String = buildString {\n"
            "        text.codePoints().forEach { append(folds[it] ?: String(Character.toChars(it))) }\n"
            "    }\n}\n")


