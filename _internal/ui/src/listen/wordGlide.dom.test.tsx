it('keeps one overlay across words and paragraphs, trimming punctuation while preserving text', async () => {
  const text = '“Nghĩ văn, chuyện. ...!? nhẹ-nhàng';
  const clock = new Clock();
  const host = document.createElement('div'); document.body.append(host);
  vi.spyOn(HTMLElement.prototype, 'getBoundingClientRect').mockImplementation(function(this: HTMLElement) {
    const word = Number(this.closest<HTMLElement>('[data-word-index]')?.dataset.wordIndex ?? 0);
    return { x: word*60, y:0, left:word*60, top:0, width:40, height:24, right:word*60+40, bottom:24, toJSON() {} };
  });
  const root = createRoot(host);
  const script: Script = { chapterId:1, title:'', duration:5, timed:true, segments:[{ id:0, paragraph:0, text, kind:'narration', speaker:'', status:'done', start:0, end:5, words:[[0,500],[500,1000],[1000,1500],[1500,2000],[2000,2500]] }] };
  await act(async () => root.render(<ClockContext.Provider value={clock}><ReadAlongText script={script} playingIndex={0} focusIndex={0} headingClassName="" /></ClockContext.Provider>));
  expect(host.querySelectorAll('[data-word-glide]')).toHaveLength(1);
  const ink = host.querySelector<HTMLElement>('[data-word-glide]')!;
  expect(host.querySelector('.is-lit [data-word-ink]')?.textContent).toBe('Nghĩ');
  await act(async () => clock.set(.6));
  expect(host.querySelector('[data-word-glide]')).toBe(ink);
  expect(host.querySelector('.is-lit [data-word-ink]')?.textContent).toBe('văn');
  await act(async () => clock.set(1.6));
  expect(host.querySelector('.is-lit [data-word-ink]')?.textContent).toBe('chuyện');
  expect(host.textContent?.trim()).toBe(text);
  await act(async () => clock.set(3));
  expect(ink.style.opacity).toBe('0');
  await act(async () => root.unmount()); host.remove();
});
it('moves one element to the exact final word rectangle and shrinks at a line break', () => {
  const ink = document.createElement('span');
  document.body.append(ink);
  const animate = vi.fn();
  ink.animate = animate;
  const first = { x: 10, y: 20, width: 32, height: 24 };
  const next = { x: 48, y: 20, width: 64, height: 24 };
  moveWordInk(ink, first, null, 120, false);
  expect(animate).not.toHaveBeenCalled();
  moveWordInk(ink, next, first, 80, true);
  expect(ink.style.transform).toBe('translate(48px, 20px)');
  expect(ink.style.width).toBe('64px');
  expect(animate.mock.calls[0][1]).toEqual({ duration: 80, easing: EASE.standard });
  moveWordInk(ink, { ...first, y: 60 }, next, 90, true);
  const frames = animate.mock.calls[1][0];
  expect(frames[1].width).toBe('0px');
  expect(frames[2].width).toBe('0px');
  expect(frames[1].offset).toBe(0.5);
  expect(frames[2].offset).toBe(0.5);
  expect(frames[0].easing).toBe(EASE.standard);
  expect(frames[2].easing).toBe(EASE.standard);
  expect(animate.mock.calls[1][1]).toEqual({ duration: 90, easing: 'linear' });
  expect(frames[1].transform).not.toBe(frames[2].transform);
  ink.remove();
});
