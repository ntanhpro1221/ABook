"""Generate UI copy for web, Compose and Qt from ui_strings/vi.json.

No locale fallback: this application has one language. Numbered slots are values,
never executable expressions. Consumers retain ownership of data and formatting.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "ui_strings/vi.json"
KT = ROOT / "mobile/android/app/src/main/java/vn/abook/player/UiStrings.kt"
TS = ROOT / "ui/src/shared/strings.generated.ts"
JS = ROOT / "desktop_qt/qml/UiStrings.js"
XML = ROOT / "mobile/android/app/src/main/res/values/strings.xml"
CPP = ROOT / "desktop_qt/src/uistrings.generated.h"


def catalog():
    return json.loads(SOURCE.read_text(encoding="utf-8"))


def slots(value):
    return sorted({int(x) for x in re.findall(r"\{(\d+)\}", value)})


def quote(value):
    return json.dumps(value, ensure_ascii=False)


def expression(value, lang):
    parts = re.split(r"(\{\d+\})", value)
    return " + ".join((f"String(p{p[1:-1]})" if lang != "kt" else f"p{p[1:-1]}.toString()")
                      if re.fullmatch(r"\{\d+\}", p) else quote(p).replace("$", "\\$") if lang == "kt" else quote(p)
                      for p in parts if p) or '""'


def outputs():
    data = catalog()
    entries = data["strings"]
    assert len(entries) == len(set(entries.values())), 'Duplicate UI copy: reuse its existing key'
    def used(folder, extensions, excluded):
        return {key for path in folder.rglob('*') if path.suffix in extensions and path.name not in excluded and '.test.' not in path.name
                for key in re.findall(r'\bS\.(s_[a-z0-9_]+)', path.read_text(encoding='utf-8'))}
    kt_keys = used(KT.parent, {'.kt'}, {'UiStrings.kt'})
    ts_keys = used(ROOT/'ui/src', {'.ts', '.tsx'}, {'strings.generated.ts'})
    js_keys = used(JS.parent, {'.qml', '.js'}, {'UiStrings.js'})
    unknown = (kt_keys | ts_keys | js_keys) - entries.keys()
    assert not unknown, f'Unknown UI keys: {sorted(unknown)}'
    kt = ["// Generated by scripts/gen_ui_strings.py. Edit ui_strings/vi.json.", "package vn.abook.player", "", "internal object S {"]
    ts = ["// Generated by scripts/gen_ui_strings.py. Edit ui_strings/vi.json.", "export const S = {"]
    js = ["// Generated by scripts/gen_ui_strings.py. Edit ui_strings/vi.json.", ".pragma library"]
    for key, value in entries.items():
        assert re.fullmatch(r"s_[a-z0-9_]+", key), key
        args = slots(value)
        assert args == list(range(len(args))), (key, args)
        if args:
            names = ", ".join(f"p{i}" for i in args)
            if key in kt_keys: kt.append(f"    fun {key}({', '.join(f'p{i}: Any?' for i in args)}): String = {expression(value, 'kt')}")
            if key in ts_keys: ts.append(f"  {key}: ({', '.join(f'p{i}: unknown' for i in args)}) => {expression(value, 'ts')},")
            if key in js_keys: js.append(f"function {key}({names}) {{ return {expression(value, 'js')}; }}")
        else:
            if key in kt_keys: kt.append(f"    const val {key} = {quote(value).replace(chr(36), chr(92) + chr(36))}")
            if key in ts_keys: ts.append(f"  {key}: {quote(value)},")
            if key in js_keys: js.append(f"var {key} = {quote(value)};")
    kt += ["}", ""]
    ts += ["} as const;", ""]
    js += [""]
    xml = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Generated by scripts/gen_ui_strings.py. -->', '<resources>']
    for name, key in data["android_resources"].items():
        value = entries[key]
        # Android's resource parser interprets quotes and apostrophes even in XML.
        value = escape(value).replace("'", "\\'").replace('"', '\\"')
        xml.append(f'    <string name="{name}" formatted="false">{value}</string>')
    xml += ["</resources>", ""]
    cpp = ['// Generated by scripts/gen_ui_strings.py.', '#pragma once', '#include <QString>', 'namespace UiStrings {']
    for key in data.get('cpp_strings', []):
        assert not slots(entries[key]), key
        cpp.append(f'inline const QString {key} = QString::fromUtf8({quote(entries[key])});')
        cpp.append(f'inline constexpr const char {key}_utf8[] = {quote(entries[key])};')
    cpp += ['}', '']
    return {KT: "\n".join(kt), TS: "\n".join(ts), JS: "\n".join(js), XML: "\n".join(xml), CPP: '\n'.join(cpp)}


def main(argv):
    stale = []
    for path, content in outputs().items():
        if "--check" in argv:
            if not path.exists() or path.read_bytes() != content.encode("utf-8"):
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            encoded=content.encode("utf-8")
            if not path.exists() or path.read_bytes()!=encoded:
                path.write_bytes(encoded)
    if stale:
        print("Stale UI strings: " + ", ".join(stale), file=sys.stderr)
    print(f"UI strings: {len(catalog()['strings'])} keys; {len(outputs())} outputs; {len(stale)} stale")
    return bool(stale)


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
