"""Generate native constants from the single playback tone catalog."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def generate():
    data = json.loads((ROOT/'abook/webui/assets/tone_presets.json').read_text(encoding='utf-8'))
    nums = lambda xs: ', '.join(str(float(x)) for x in xs)
    kt = ['// Generated by scripts/gen_tone_presets.py; edit tone_presets.json.',
          'package vn.abook.player', 'object ToneCatalog {',
          f'    const val Q = {data["q"]}',
          f'    val frequencies = doubleArrayOf({nums(data["frequencies"])})',
          '    val presets = listOf(']
    kt += [f'        TonePreset("{p["id"]}", S.{p["label"]}, listOf({nums(p["bands"])}))'+(',' if i<len(data['presets'])-1 else '') for i,p in enumerate(data['presets'])]
    kt += ['    )', '}']
    cpp = ['// Generated by scripts/gen_tone_presets.py; edit tone_presets.json.', '#pragma once',
           '#include <array>', 'namespace ToneCatalog {',f'inline constexpr double q = {data["q"]};',
           f'inline constexpr std::array<double,5> frequencies{{{nums(data["frequencies"])}}};',
           'struct Preset { const char *id; const char *label; std::array<double,5> bands; };',
           f'inline constexpr std::array<Preset,{len(data["presets"])}> presets{{{{']
    cpp += [f'    {{"{p["id"]}", "{p["label"]}", {{{nums(p["bands"])}}}}},' for p in data['presets']]
    cpp += ['}};', '}']
    ts = ['// Generated by scripts/gen_tone_presets.py; edit tone_presets.json.',
          "import { S } from '@/shared/strings.generated';", 'export const TONE_NAMES = {']
    ts += [f'    {p["id"]}: S.{p["label"]},' for p in data['presets']]
    ts += ['} as const;']
    js = ['// Generated by scripts/gen_tone_presets.py; edit tone_presets.json.', '.pragma library', '.import "UiStrings.js" as S',
          'function label(id) {', '    switch(id) {']
    js += [f'    case "{p["id"]}": return S.{p["label"]};' for p in data['presets']]
    js += ['    default: return "";', '    }', '}']
    for path,lines in [('mobile/android/app/src/main/java/vn/abook/player/ToneCatalog.generated.kt',kt),('desktop_qt/src/tonecatalog.generated.h',cpp),
                       ('ui/src/listen/toneLabels.generated.ts',ts),('desktop_qt/qml/ToneLabels.js',js)]:
        target=ROOT/path; text='\n'.join(lines)+'\n'
        if not target.exists() or target.read_text(encoding='utf-8')!=text: target.write_text(text,encoding='utf-8',newline='\n')

if __name__=='__main__': generate()
